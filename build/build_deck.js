const LX = 0.67;
const LW = 1.55;
const CX = 2.32;
const CW = 10.34;
const lh = (pt, ls = 0.9) => (pt * 1.448 * ls) / 72;

function frame(n, title, subtitle, sources, notes) {
  const s = pres.addSlide({ masterName: "GFF" });
  T.text(s, `전시산업론 중간고사 개인 과제   ${n}`, { x: 0.67, y: 0.3, w: 6, h: 0.26 }, { size: 11, color: C.MUTED, name: "과제 표기" });
  s.addText(title, { placeholder: "title" });
  s.addText(subtitle, { placeholder: "subtitle" });
  if ([].concat(sources).length) T.text(s, sources, { x: 0.67, y: 6.95, w: 11.99, h: 0.5 }, { size: 7, color: C.MUTED, ls: 0.9, name: "출처" });
  s.addNotes(notes.join("\n\n"));
  return s;
}

function label(s, lines, y, sub) {
  lines = [].concat(lines);
  T.text(s, lines, { x: LX, y, w: LW, h: 0.26 * lines.length }, { size: 12, bold: true, color: C.NAVY, ls: 1, name: "라벨" });
  if (sub) {
    sub = [].concat(sub);
    T.text(s, sub, { x: LX, y: y + 0.27 * lines.length + 0.02, w: LW, h: Math.max(0.6, sub.length * lh(8, 0.92) + 0.05) }, { size: 8, color: C.MUTED, name: "라벨 안내" });
  }
}

